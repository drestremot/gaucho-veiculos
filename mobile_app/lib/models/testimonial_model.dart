class TestimonialModel {
  final int id;
  final String name;
  final String city;
  final String car;
  final int rating;
  final String date;
  final String avatar;
  final String comment;

  const TestimonialModel({
    required this.id,
    required this.name,
    required this.city,
    required this.car,
    required this.rating,
    required this.date,
    required this.avatar,
    required this.comment,
  });
}

